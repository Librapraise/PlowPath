export function getTranslation(locale: Locale, key: string, variables?: Record<string, string | number>): string {
  let dict = translations[locale] as any;
  if (!dict || !dict[key]) {
    const dynDict = generalDynamicTranslations[locale];
    if (dynDict && dynDict[key]) {
      dict = dynDict;
    } else {
      if (locale.startsWith('en')) {
        dict = translations['en-CA'] as any;
      } else {
        dict = translations['fr-QC'] as any;
      }
    }
  }

  let text = dict[key] || (generalDynamicTranslations[locale] && generalDynamicTranslations[locale][key]) || (translations['en-CA'] as any)[key] || key;

  // Apply US/UK spelling variations dynamically if needed
  if (locale === 'en-US') {
    text = text
      .replace(/colour/g, 'color')
      .replace(/Colour/g, 'Color')
      .replace(/centre/g, 'center')
      .replace(/Centre/g, 'Center')
      .replace(/cheque/g, 'check')
      .replace(/favour/g, 'favor')
      .replace(/realise/g, 'realize')
      .replace(/programme/g, 'program');
  } else if (locale === 'en-GB') {
    text = text
      .replace(/color/g, 'colour')
      .replace(/Color/g, 'Colour')
      .replace(/center/g, 'centre')
      .replace(/Center/g, 'Centre')
      .replace(/check/g, 'cheque')
      .replace(/favor/g, 'favour')
      .replace(/realize/g, 'realise')
      .replace(/program/g, 'programme');
  }

  if (variables) {
    Object.keys(variables).forEach((v) => {
      text = text.replace(new RegExp(`{{${v}}}`, 'g'), String(variables[v]));
    });
  }

  return text;
}

export function useTranslation() {
  const language = useSettingsStore((s) => s.language) || 'fr-QC';
  const t = (key: string | keyof typeof translations['fr-QC'], variables?: Record<string, string | number>) => {
    return getTranslation(language, key, variables);
  };

  const formatDate = (date: Date) => {
    if (language === 'fr-QC') {
      const months = [
        'janvier', 'février', 'mars', 'avril', 'mai', 'juin',
        'juillet', 'août', 'septembre', 'octobre', 'novembre', 'décembre'
      ];
      return `${date.getDate()} ${months[date.getMonth()]} ${date.getFullYear()}`;
    }
    if (language === 'en-CA') {
      // YYYY-MM-DD
      const m = String(date.getMonth() + 1).padStart(2, '0');
      const d = String(date.getDate()).padStart(2, '0');
      return `${date.getFullYear()}-${m}-${d}`;
    }
    if (language === 'en-US') {
      // MM/DD/YYYY
      const m = String(date.getMonth() + 1).padStart(2, '0');
      const d = String(date.getDate()).padStart(2, '0');
      return `${m}/${d}/${date.getFullYear()}`;
    }
    // en-GB (DD/MM/YYYY)
    const m = String(date.getMonth() + 1).padStart(2, '0');
    const d = String(date.getDate()).padStart(2, '0');
    return `${d}/${m}/${date.getFullYear()}`;
  };

  const formatCurrency = (amount: number | string | null | undefined) => {
    const parsed = typeof amount === 'number' ? amount : parseFloat(String(amount || 0));
    const num = isNaN(parsed) ? 0 : parsed;
    if (language === 'fr-QC') {
      return `${num.toFixed(2).replace('.', ',')} $`;
    }
    if (language === 'en-GB') {
      return `£${num.toFixed(2)}`;
    }
    return `$${num.toFixed(2)}`;
  };

  return { t, locale: language, formatDate, formatCurrency };
}
